-- هذا الملف SQL جاهز للتشغيل اليدوي على Supabase SQL Editor فقط.
-- لم يُشغَّل من قبل Claude — لا يوجد اتصال مباشر بقاعدة البيانات بهذه الجلسة.
-- تعديل واحد فقط: إضافة عمود audit_access لجدول public.user_screen_permissions
-- الموجود مسبقاً (Batch 1). لا تعديل على RLS، لا تعديل على أي جدول آخر، لا تعديل
-- على أي صف موجود (القيمة الافتراضية false لكل الصفوف الحالية).
--
-- الغرض: صلاحية "تدقيق" (Audit Access) مستقلة تماماً (orthogonal) عن العمود الحالي
-- permission (VIEW/INPUT/ADMIN) — تتيح الوصول لدليل القرار (Decision Evidence) على
-- شاشة "المشتريات الخارجية الذكية" فقط، بدون أي صلاحية تشغيل/تعديل. الإنفاذ الفعلي
-- بمستوى الدالة داخل كود الشاشة نفسها (hasAuditAccess()/myAuditAccess) — هذا العمود
-- فقط يخزّن القيمة، ولا يضيف أي RLS جديدة.
--
-- ⚠️ قيد مهم بالسكيما الحالية (Batch 1): permission NOT NULL CHECK (VIEW/INPUT/ADMIN)
-- يعني إنه ما ممكن يكون صف بـ audit_access=true وبدون صلاحية أساسية صالحة — الحد الأدنى
-- الواقعي لحساب "تدقيق فقط" هو permission='VIEW' مع audit_access=true (وليس صف بلا
-- permission إطلاقاً). شاشة إدارة المستخدمين والصلاحيات تُعطِّل خانة "تدقيق" تلقائياً
-- على أي خلية NONE لنفس السبب.
-- ============================================================================

alter table public.user_screen_permissions
  add column if not exists audit_access boolean not null default false;

