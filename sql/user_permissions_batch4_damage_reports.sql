-- شاشة جديدة كلياً (لا مستخدمين فعليين عليها اليوم) — نُفّذت أصلاً بمشروع منفصل
-- (Node/Express + PostgreSQL على Railway) وهذا الملف ينقلها لبنية الكيلاني
-- الموحّدة على Supabase، بجداول جديدة بالكامل ولا يعدّل أي جدول موجود مسبقاً.
-- يستبدل ملف "damage-schema.sql" الأصلي (سياسات RLS فيه كانت placeholder عامة
